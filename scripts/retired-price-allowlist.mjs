/**
 * Files permitted to contain retired price tokens, and why.
 *
 * CLAUDE.md bans publishing $99, $119, $129, $135, $149, $175, $176, $225,
 * $275, and $400 as Offer prices. validate-policy-truth.mjs scans every
 * .astro/.ts file under src/ for them; this list is the only escape, so a new
 * file cannot fall outside coverage by being forgotten.
 *
 * Entries are occurrence-counted on purpose. Allowlisting a whole file would
 * mean a genuinely new bad price added to that file later passes unnoticed —
 * `count` makes any change to the number of tokens fail the build and force a
 * fresh look. A count that drops is a failure too: the entry is stale and
 * should be trimmed or removed.
 *
 * Types:
 *   source     — non-rendered narration (module comments about retired values)
 *   attributed — someone else's figure (competitor, market survey, landlord
 *                deduction). Requires contextPattern, checked per occurrence
 *                rather than per file: every retired figure must have the
 *                attribution wording within ATTRIBUTION_WINDOW characters of
 *                it. A file-wide test would only prove one attribution phrase
 *                survives somewhere, so in a file holding several figures one
 *                could quietly lose its attribution and still read as a TVCT
 *                Offer. Figures attributed by table position rather than by
 *                prose declare structuralPattern (matching the occurrence's own
 *                line) plus structuralAnchor (the structure it depends on),
 *                so that justification is stated rather than inferred.
 *   pending    — blocked on an unanswered question. Requires owner, question,
 *                and expires. Past the expiry date the build fails rather than
 *                letting the debt go quiet.
 *   deferred   — known, scheduled editorial work. Requires tracking and
 *                expires, with the same expiry behaviour as pending.
 *
 * Kept separate from validate-policy-truth.mjs so the validator stays readable
 * and this list can be reviewed on its own as the standing debt register.
 */

